#!/usr/bin/env python3
"""gen-tables.py - extract the tables of the original Algol-GDR from overlay ALGOL.

    gen-tables.py [MONSYS9] > src/tables_data.cpp

MONSYS9 is the Dubna system tape (default ../os-dubna/monsys/monsys.9). The overlay
ALGOL is read from it as os-dubna/algol/Makefile does, and loads at 01604.
See doc/tables.md for the meaning of each table.
"""
import os
import sys

BASE = 0o1604
OVERLAY = (0o070 * 1024 + 0o1100) * 6  # zone, word of the RLE stream

# name, first, last, text comments, description
TABLES = [
    ('symattr', 0o15146, 0o15413, False, 'pass 1: symbol attributes, then its M7 constants'),
    ('warnings', 0o16506, 0o16513, True, "pass 1: 'WARNING SYMBOL AFTER END', 'HET ′EOP′ !'"),
    ('commsg', 0o16045, 0o16071, True, "pass 1: 'COMMON' error messages, 3 words each"),
    ('chclass', 0o16514, 0o16713, False, 'pass 1: character classes, by 8-bit code'),
    ('syntext', 0o17106, 0o17165, True, 'pass 1: pieces of the syntax error texts'),
    ('errclass', 0o17166, 0o17202, False, 'pass 1: error classes, 6 bits per error'),
    ('p2msg', 0o21670, 0o21717, True, 'pass 2: semantic error messages'),
    ('p2disp', 0o21720, 0o22025, False, 'pass 2: dispatch by item code 000-0105'),
    ('p3class', 0o22264, 0o22272, False, 'pass 3: classes of item codes, FOR scan'),
    ('p3mask', 0o22301, 0o22301, False, 'pass 3: mask of allowed codes'),
    ('p3rewr', 0o22365, 0o22402, False, 'pass 3: rewrite handlers by item code'),
    ('p3jump', 0o22407, 0o22421, False, 'pass 3: jump table of the rewrite handlers'),
    ('p3regs', 0o23154, 0o23163, False, 'pass 3: index registers for loop subscripts'),
    ('template_', 0o25747, 0o26055, False, 'pass 4: instruction templates, 4444 = operand'),
    ('p4disp', 0o26056, 0o26151, False, 'pass 4: dispatch, two item codes per word'),
    ('linetab', 0o26601, 0o26616, True, 'pass 5: line table format, PROGRAM TOO LONG, heading'),
    ('isotext', 0o30060, 0o30117, False, 'ISO to TEXT code ranges'),
    ('rtnames', 0o30124, 0o30255, False, 'run-time names in TEXT code'),
    ('summary', 0o30333, 0o30354, True, 'format of PROGRAM ДЛИHA: ...'),
]
WORKSPACE = (0o1736, 0o5777)    # initialized data, nonzero words only


def ovl2bin(data):
    def word(i):
        return int.from_bytes(data[i:i + 6], 'big')
    out = []
    i = 0
    while True:
        h = word(i)
        i += 6
        flag, rep, cnt = h >> 47, (h >> 15) & 0o77777, h & 0o77777
        if rep == 0 and cnt == 0:
            return out
        fill = 0
        if flag and rep:
            fill = word(i)
            i += 6
        for _ in range(cnt):
            out.append(word(i))
            i += 6
        out += [fill] * rep


def iso(w):
    return ''.join(chr(c) if 32 <= c < 127 and c != 0x5c else '.'
                   for c in w.to_bytes(6, 'big'))


def main():
    here = os.path.dirname(os.path.realpath(__file__))
    tape = sys.argv[1] if len(sys.argv) > 1 else \
        os.path.join(here, '../../os-dubna/monsys/monsys.9')
    with open(tape, 'rb') as f:
        f.seek(OVERLAY)
        img = ovl2bin(f.read())

    def at(a):
        return img[a - BASE]

    p = print
    p('// Generated by scripts/gen-tables.py from overlay ALGOL of monsys.9. Do not edit.')
    p('// Comments give the original addresses (octal).')
    p('// clang-format off')
    p('#include "tables.h"')
    p()
    p('namespace tables {')
    p()
    p(f'// {WORKSPACE[0]:05o}-{WORKSPACE[1]:05o}: data set before the passes run, nonzero words')
    p('const InitWord workspace_init[] = {')
    for a in range(WORKSPACE[0], WORKSPACE[1] + 1):
        if at(a):
            p(f'    {{ 0{a:05o}, 0{at(a):016o} }},')
    p('};')
    p('const size_t workspace_init_size = std::size(workspace_init);')
    for name, lo, hi, text, desc in TABLES:
        p()
        p(f'// {lo:05o}-{hi:05o}: {desc}')
        p(f'static const Word {name}_words[] = {{')
        for a in range(lo, hi + 1):
            c = f'{a:05o}' + (f' {iso(at(a))}' if text else '')
            p(f'    0{at(a):016o}, // {c}')
        p('};')
        p(f'const Table {name}{{ 0{lo:05o}, {name}_words }};')
    p()
    p('} // namespace tables')


main()
